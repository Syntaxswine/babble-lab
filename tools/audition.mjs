#!/usr/bin/env node
// Every preset saying the same few lines, as WAVs plus one page of players.
// The tests measure; this is for the one instrument they cannot replace — an ear.
//
//   node tools/audition.mjs            -> audition/index.html  (open it; no server needed)

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { render, encodeWav, PRESETS, resolveVoice } from '../src/index.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'audition');
fs.mkdirSync(dir, { recursive: true });

const LINES = [
  ['greeting', 'Welcome to the village, stranger! Have you seen my little brother anywhere?'],
  ['moods', 'Really? No way. NO WAY! Hmm... fine.'],
];
const TONGUES = [['english-ish (tongue 0)', 0], ['tongue 42', 42], ['tongue 7', 7]];
const esc = (s) => s.replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));

let rows = '';
for (const name of Object.keys(PRESETS)) {
  const v = resolveVoice(name);
  let cells = '';
  for (const [tag, text] of LINES) {
    const file = `${name}.${tag}.wav`;
    const { samples, sampleRate } = render(text, name);
    fs.writeFileSync(path.join(dir, file), encodeWav(samples, sampleRate));
    cells += `<td><audio controls preload="none" src="${file}"></audio></td>`;
  }
  rows += `<tr><th>${name}</th><td class="dim">${v.mode} &middot; ${v.pitch} Hz &middot; ${esc(PRESETS[name].note ?? '')}</td>${cells}</tr>\n`;
  console.log(name);
}

let tongueRows = '';
for (const [label, tongue] of TONGUES) {
  const file = `narrator.tongue-${tongue}.wav`;
  const { samples, sampleRate, plan } = render(LINES[0][1], { tongue });
  fs.writeFileSync(path.join(dir, file), encodeWav(samples, sampleRate));
  const said = plan.units.filter((u) => u.kind !== 'rest').map((u) => u.label).join(' ');
  tongueRows += `<tr><th>${label}</th><td class="dim">${esc(said)}</td><td><audio controls preload="none" src="${file}"></audio></td></tr>\n`;
}

fs.writeFileSync(path.join(dir, 'index.html'), `<!doctype html><meta charset="utf-8"><title>babble-lab audition</title>
<style>body{font:12px/1.5 ui-monospace,Consolas,monospace;background:#f6f3ea;color:#2b2a27;padding:16px 20px}h1{font-size:14px}h2{font-size:11px;letter-spacing:.08em;text-transform:uppercase;color:#5b6b73;margin-top:22px}
table{border-collapse:collapse}th{text-align:left;padding-right:14px}td,th{border-bottom:1px dotted #cfc9b8;padding:3px 10px 3px 0;vertical-align:middle}.dim{color:#7d786b;max-width:420px}audio{height:28px;width:230px}</style>
<h1>babble-lab &middot; audition</h1>
<p class="dim">Generated by <code>node tools/audition.mjs</code>. Same lines through every preset.</p>
<h2>presets</h2>
<table><tr><th></th><th></th>${LINES.map(([, t]) => `<th class="dim">${esc(t)}</th>`).join('')}</tr>
${rows}</table>
<h2>one voice, three tongues</h2>
<p class="dim">Same text, same voice. A tongue permutes sounds within their manner class: the rhythm stays, the words go.</p>
<table>${tongueRows}</table>
`);
console.log(`\n${path.join('audition', 'index.html')}`);
