#!/usr/bin/env node
// Two files that need nothing else:
//
//   dist/babble-lab.html     the workbench, engine inlined. Double-click it: ES
//                            modules cannot load from file://, one inline script can.
//   dist/babble.global.js    the engine + runtime as a classic script -> globalThis.Babble,
//                            for games that are not built from ES modules (Twine/SugarCube,
//                            a plain <script> tag).
//
// This is a bundler for THIS codebase's import/export style and nothing more:
// single-line statements in the four shapes below. Anything else is refused,
// loudly — a bundler that guesses produces a file that fails somewhere else.
// Output is deterministic (no timestamps), so test/build.test.mjs can prove
// dist/ is current by rebuilding and comparing bytes.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rel = (abs) => path.relative(root, abs).split(path.sep).join('/');

const IMPORT = /^import \{([^}]*)\} from '(\.[^']+)';\s*$/;
const REEXPORT = /^export \{([^}]*)\} from '(\.[^']+)';\s*$/;
const EXPORT_LIST = /^export \{([^}]*)\};\s*$/;
const EXPORT_DECL = /^export (async function\*?|function\*?|const|let|class) ([A-Za-z_$][\w$]*)/;

const names = (list) => list.split(',').map((s) => s.trim()).filter(Boolean).map((s) => { const [from, to] = s.split(/\s+as\s+/); return { from, to: to ?? from }; });

function loadModule(abs, seen, order) {
  const id = rel(abs);
  if (seen.has(id)) { if (seen.get(id) === 'open') throw new Error(`build: import cycle through ${id}`); return; }
  seen.set(id, 'open');
  const src = fs.readFileSync(abs, 'utf8').replace(/\r\n/g, '\n');
  if (/<\/script/i.test(src)) throw new Error(`build: ${id} contains "</script", which would end the inline script early`);
  const body = [];
  const exportsOut = []; // [exportedName, expression]
  for (const line of src.split('\n')) {
    let m;
    if ((m = line.match(IMPORT))) {
      const dep = path.resolve(path.dirname(abs), m[2]);
      loadModule(dep, seen, order);
      body.push(`const { ${names(m[1]).map((n) => (n.from === n.to ? n.from : `${n.from}: ${n.to}`)).join(', ')} } = __m[${JSON.stringify(rel(dep))}];`);
    } else if ((m = line.match(REEXPORT))) {
      const dep = path.resolve(path.dirname(abs), m[2]);
      loadModule(dep, seen, order);
      for (const n of names(m[1])) exportsOut.push([n.to, `__m[${JSON.stringify(rel(dep))}].${n.from}`]);
      body.push('');
    } else if ((m = line.match(EXPORT_LIST))) {
      for (const n of names(m[1])) exportsOut.push([n.to, n.from]);
      body.push('');
    } else if ((m = line.match(EXPORT_DECL))) {
      exportsOut.push([m[2], m[2]]);
      body.push(line.replace(/^export /, ''));
    } else if (/^(import|export)\b/.test(line)) {
      throw new Error(`build: ${id}: a module statement this bundler does not understand:\n    ${line}`);
    } else if (/^#!/.test(line)) body.push('');
    else body.push(line);
  }
  seen.set(id, 'done');
  order.push({ id, code: `__m[${JSON.stringify(id)}] = (() => {\n${body.join('\n')}\nreturn { ${exportsOut.map(([k, v]) => (k === v ? k : `${k}: ${v}`)).join(', ')} };\n})();` });
}

export function bundle(entries) {
  const seen = new Map();
  const order = [];
  for (const e of entries) loadModule(path.resolve(root, e), seen, order);
  return `const __m = Object.create(null);\n${order.map((m) => `// ---- ${m.id}\n${m.code}`).join('\n')}\n`;
}

export function buildAll() {
  const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8').replace(/\r\n/g, '\n');
  const css = fs.readFileSync(path.join(root, 'workbench/style.css'), 'utf8').replace(/\r\n/g, '\n');
  const linkTag = '<link rel="stylesheet" href="workbench/style.css">';
  const scriptTag = '<script type="module" src="workbench/app.mjs"></script>';
  if (!html.includes(linkTag) || !html.includes(scriptTag)) throw new Error('build: index.html no longer has the stylesheet link / module script this build replaces');
  const page = html
    .replace(linkTag, () => `<style>\n${css}</style>`)
    .replace(scriptTag, () => `<script type="module">\n${bundle(['workbench/app.mjs'])}</script>`);

  const lib = `// babble-lab, as one classic script. Generated by tools/build-standalone.mjs — edit src/, not this.\n//   <script src="babble.global.js"></script>\n//   const { samples } = Babble.render('Who goes there?', 'gruff');\n//   const speaker = Babble.createSpeaker(audioContext);\n(function () {\n'use strict';\n${bundle(['src/index.mjs', 'src/runtime.mjs'])}globalThis.Babble = Object.assign({}, __m['src/index.mjs'], __m['src/runtime.mjs']);\n})();\n`;
  return { 'dist/babble-lab.html': page, 'dist/babble.global.js': lib };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = buildAll();
  fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
  for (const [file, text] of Object.entries(out)) { fs.writeFileSync(path.join(root, file), text); console.log(`${file}  ${(text.length / 1024).toFixed(0)} kB`); }
}
